CREATE TABLE CMS_CONTENT_I18N_TB (
    ENTITY_TYPE   VARCHAR2(30 CHAR) NOT NULL,
    ENTITY_ID     NUMBER(12, 0) NOT NULL,
    LOCALE        VARCHAR2(10 CHAR) NOT NULL,
    STATUS        VARCHAR2(12 CHAR) DEFAULT 'DRAFT' NOT NULL,
    PAYLOAD_JSON  CLOB NOT NULL,
    UPDATED_AT    DATE DEFAULT SYSDATE NOT NULL,
    UPDATED_BY    VARCHAR2(100 CHAR),
    CONSTRAINT PK_CMS_CONTENT_I18N PRIMARY KEY (ENTITY_TYPE, ENTITY_ID, LOCALE),
    CONSTRAINT CK_CMS_I18N_TYPE CHECK (ENTITY_TYPE IN ('EVENT','FAQ','DETAIL_CATEGORY','DETAIL_PAGE','DETAIL_SECTION')),
    CONSTRAINT CK_CMS_I18N_LOCALE CHECK (LOCALE IN ('en','ja','zh-CN','zh-TW')),
    CONSTRAINT CK_CMS_I18N_STATUS CHECK (STATUS IN ('DRAFT','PUBLISHED')),
    CONSTRAINT CK_CMS_I18N_JSON CHECK (PAYLOAD_JSON IS JSON)
);

CREATE INDEX IX_CMS_I18N_PUBLIC
    ON CMS_CONTENT_I18N_TB (ENTITY_TYPE, LOCALE, STATUS, ENTITY_ID);

COMMENT ON TABLE CMS_CONTENT_I18N_TB IS 'AHNS CMS 개별 게시물 언어별 번역(한국어 원문은 기존 테이블)';
COMMENT ON COLUMN CMS_CONTENT_I18N_TB.PAYLOAD_JSON IS '타입별 허용 텍스트 필드만 포함한 JSON';

-- 적용 검증
SELECT TABLE_NAME FROM USER_TABLES WHERE TABLE_NAME = 'CMS_CONTENT_I18N_TB';
