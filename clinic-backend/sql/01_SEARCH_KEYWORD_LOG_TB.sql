-- IP, 회원 ID, User-Agent 등 개인 식별자는 이 테이블에 저장하지 않습니다.

CREATE TABLE SEARCH_KEYWORD_LOG_TB (
    LOG_IDX NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    KEYWORD VARCHAR2(100 CHAR) NOT NULL,
    SEARCHED_AT TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL
);

-- 최근 7일 조회 성능 개선
CREATE INDEX IX_SEARCH_KEYWORD_LOG_DATE
    ON SEARCH_KEYWORD_LOG_TB (SEARCHED_AT, KEYWORD);

-- 적용 확인
SELECT TABLE_NAME
FROM USER_TABLES
WHERE TABLE_NAME = 'SEARCH_KEYWORD_LOG_TB';

-- 최근 7일 실제 검색 빈도 TOP 5 확인
SELECT KEYWORD, COUNT(*) AS SEARCH_COUNT
FROM SEARCH_KEYWORD_LOG_TB
WHERE SEARCHED_AT >= LOCALTIMESTAMP - INTERVAL '7' DAY
GROUP BY KEYWORD
ORDER BY SEARCH_COUNT DESC, KEYWORD ASC
FETCH FIRST 5 ROWS ONLY;

