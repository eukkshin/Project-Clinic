-- AHNS Account Settings / Oracle Database
-- 최초 1회만 실행. 기존 MEMBER_TB, PASSWORD_RESET_TOKEN을 수정하거나 재생성하지 않습니다.
-- SQL Developer에서는 선택 실행(F5) 또는 구문별 실행할 수 있습니다.

CREATE TABLE ACCOUNT_EMAIL_CHANGE_TOKEN (
    ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_IDX       NUMBER NOT NULL,
    TOKEN_HASH     VARCHAR2(64) NOT NULL,
    OLD_EMAIL      VARCHAR2(100) NOT NULL,
    NEW_EMAIL      VARCHAR2(100) NOT NULL,
    CREATED_AT     TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
    EXPIRES_AT     TIMESTAMP NOT NULL,
    USED_AT        TIMESTAMP,
    CONSTRAINT UQ_ACC_EMAIL_TOKEN_HASH UNIQUE (TOKEN_HASH),
    CONSTRAINT FK_ACC_EMAIL_TOKEN_MEMBER FOREIGN KEY (USER_IDX) REFERENCES MEMBER_TB(USER_IDX)
);

CREATE INDEX IX_ACC_EMAIL_TOKEN_USER ON ACCOUNT_EMAIL_CHANGE_TOKEN(USER_IDX, USED_AT);

CREATE TABLE ACCOUNT_CONSENT_HISTORY (
    ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_IDX       NUMBER NOT NULL,
    CHANNEL        VARCHAR2(12) NOT NULL,
    PREVIOUS_VALUE CHAR(1) NOT NULL,
    NEW_VALUE      CHAR(1) NOT NULL,
    CHANGED_AT     TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
    SOURCE         VARCHAR2(30) DEFAULT 'ACCOUNT_SETTINGS' NOT NULL,
    CONSTRAINT CK_ACC_CONSENT_CHANNEL CHECK (CHANNEL IN ('MAIL', 'SNS')),
    CONSTRAINT CK_ACC_CONSENT_PREV CHECK (PREVIOUS_VALUE IN ('Y', 'N')),
    CONSTRAINT CK_ACC_CONSENT_NEXT CHECK (NEW_VALUE IN ('Y', 'N')),
    CONSTRAINT FK_ACC_CONSENT_MEMBER FOREIGN KEY (USER_IDX) REFERENCES MEMBER_TB(USER_IDX)
);

CREATE INDEX IX_ACC_CONSENT_USER_DATE ON ACCOUNT_CONSENT_HISTORY(USER_IDX, CHANGED_AT);

COMMENT ON TABLE ACCOUNT_EMAIL_CHANGE_TOKEN IS '회원 이메일 변경 인증용 15분 단일사용 토큰';
COMMENT ON TABLE ACCOUNT_CONSENT_HISTORY IS '회원의 선택적 소식 수신 동의 변경 이력';
