CREATE TABLE RESERVATION_TB (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  USER_IDX NUMBER NULL,
  DEPARTMENT VARCHAR2(100) NOT NULL,
  SCHEDULED_AT TIMESTAMP NOT NULL,
  SLOT_DATE VARCHAR2(10) NOT NULL,
  SLOT_TIME VARCHAR2(5) NOT NULL,
  STATUS VARCHAR2(20) DEFAULT '예약확정' NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  MEMO VARCHAR2(1000),
  CONTACT_NAME VARCHAR2(80),
  CONTACT_PHONE VARCHAR2(30),
  SOURCE VARCHAR2(12) DEFAULT 'MEMBER' NOT NULL,
  CONSTRAINT FK_RESERVATION_MEMBER FOREIGN KEY (USER_IDX) REFERENCES MEMBER_TB(USER_IDX),
  CONSTRAINT CK_RESERVATION_STATUS CHECK (STATUS IN ('예약대기','예약확정','방문완료','취소')),
  CONSTRAINT CK_RESERVATION_SOURCE CHECK (SOURCE IN ('MEMBER','MANUAL'))
);
CREATE INDEX IX_RESERVATION_MEMBER_DATE ON RESERVATION_TB (USER_IDX, SCHEDULED_AT);
-- 사용 중인 단일 상담 슬롯에 유효 예약은 최대 1건(회원·관리자 공통)
CREATE UNIQUE INDEX UQ_RESERVATION_ACTIVE_SLOT ON RESERVATION_TB (
  CASE WHEN STATUS IN ('예약대기','예약확정') THEN SLOT_DATE END,
  CASE WHEN STATUS IN ('예약대기','예약확정') THEN SLOT_TIME END
);

CREATE TABLE RESERVATION_BLOCK_TB (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  BLOCK_DATE VARCHAR2(10) NOT NULL,
  BLOCK_TIME VARCHAR2(5) NOT NULL,
  REASON VARCHAR2(200),
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT UQ_RESERVATION_BLOCK_DAY_TIME UNIQUE (BLOCK_DATE, BLOCK_TIME)
);
CREATE INDEX IX_RESERVATION_BLOCK_DATE ON RESERVATION_BLOCK_TB (BLOCK_DATE);

