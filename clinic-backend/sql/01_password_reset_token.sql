CREATE TABLE PASSWORD_RESET_TOKEN (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  USER_IDX NUMBER NOT NULL,
  TOKEN_HASH VARCHAR2(64) NOT NULL,
  EXPIRES_AT TIMESTAMP NOT NULL,
  USED_AT TIMESTAMP NULL,
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT FK_PW_RESET_MEMBER FOREIGN KEY (USER_IDX)
    REFERENCES MEMBER_TB (USER_IDX) ON DELETE CASCADE,
  CONSTRAINT UQ_PW_RESET_TOKEN_HASH UNIQUE (TOKEN_HASH)
);

CREATE INDEX IDX_PW_RESET_MEMBER ON PASSWORD_RESET_TOKEN (USER_IDX, USED_AT);
CREATE INDEX IDX_PW_RESET_EXPIRY ON PASSWORD_RESET_TOKEN (EXPIRES_AT);

