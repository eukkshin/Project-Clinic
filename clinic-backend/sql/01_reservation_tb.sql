-- 기존 스키마가 다르면 기존 자료를 보존하고 컬럼을 맞춰야 합니다.
-- Oracle SQL Developer에서 일반 회원 테이블과 동일한 스키마에 접속하세요.

CREATE TABLE RESERVATION_TB (
    ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_IDX     NUMBER NOT NULL,
    DEPARTMENT   VARCHAR2(100) NOT NULL,
    SCHEDULED_AT TIMESTAMP NOT NULL,
    STATUS       VARCHAR2(20) DEFAULT '예약대기' NOT NULL,
    CREATED_AT   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    MEMO         VARCHAR2(1000),
    CONSTRAINT FK_RESERVATION_MEMBER
        FOREIGN KEY (USER_IDX) REFERENCES MEMBER_TB(USER_IDX),
    CONSTRAINT CK_RESERVATION_STATUS
        CHECK (STATUS IN ('예약대기', '예약확정', '방문완료', '취소'))
);

CREATE INDEX IX_RESERVATION_MEMBER_DATE
  ON RESERVATION_TB (USER_IDX, SCHEDULED_AT);

COMMIT;
