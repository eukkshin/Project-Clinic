CREATE OR REPLACE TRIGGER TRG_CMS_I18N_DEL_EVENT
AFTER DELETE ON EVENT_RANKING_TB
FOR EACH ROW
BEGIN
  DELETE FROM CMS_CONTENT_I18N_TB WHERE ENTITY_TYPE='EVENT' AND ENTITY_ID=:OLD.EVENT_IDX;
END;
/

