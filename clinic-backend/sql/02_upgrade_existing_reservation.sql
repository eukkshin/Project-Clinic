ALTER TABLE RESERVATION_TB MODIFY (USER_IDX NULL);
ALTER TABLE RESERVATION_TB ADD (
  SLOT_DATE VARCHAR2(10),
  SLOT_TIME VARCHAR2(5),
  CONTACT_NAME VARCHAR2(80),
  CONTACT_PHONE VARCHAR2(30),
  SOURCE VARCHAR2(12) DEFAULT 'MEMBER' NOT NULL
);
-- 기존 데이터가 있는 경우 실제 DB에 저장된 시각이 한국 현지시각인지 먼저 확인하세요.
-- 아래 TO_CHAR은 SCHEDULED_AT에 한국 현지시각이 저장되었다는 전제입니다.
-- 저장 시각이 UTC이면 +9시간 보정 후 SLOT_DATE / SLOT_TIME을 채워야 합니다.
UPDATE RESERVATION_TB SET
  SLOT_DATE = TO_CHAR(SCHEDULED_AT, 'YYYY-MM-DD'),
  SLOT_TIME = TO_CHAR(SCHEDULED_AT, 'HH24:MI')
WHERE SLOT_DATE IS NULL OR SLOT_TIME IS NULL;
ALTER TABLE RESERVATION_TB MODIFY (SLOT_DATE NOT NULL, SLOT_TIME NOT NULL);

ALTER TABLE RESERVATION_TB ADD CONSTRAINT CK_RESERVATION_SOURCE
  CHECK (SOURCE IN ('MEMBER','MANUAL'));

-- 이 결과가 한 행이라도 나오면 먼저 중복 자료를 정리해야 UNIQUE INDEX 생성 가능
SELECT SLOT_DATE, SLOT_TIME, COUNT(*) AS ACTIVE_COUNT FROM RESERVATION_TB
 WHERE STATUS IN ('예약대기','예약확정')
 GROUP BY SLOT_DATE, SLOT_TIME HAVING COUNT(*) > 1;

-- 이전 02_reservation_prevent_duplicate.sql에서 만든 회원별 중복 인덱스가 있다면
-- 그 인덱스를 유지해도 되지만, 아래 전역 UNIQUE INDEX는 반드시 필요합니다.
CREATE UNIQUE INDEX UQ_RESERVATION_ACTIVE_SLOT ON RESERVATION_TB (
  CASE WHEN STATUS IN ('예약대기','예약확정') THEN SLOT_DATE END,
  CASE WHEN STATUS IN ('예약대기','예약확정') THEN SLOT_TIME END
);

CREATE TABLE RESERVATION_BLOCK_TB (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  BLOCK_DATE VARCHAR2(10) NOT NULL,
  BLOCK_TIME VARCHAR2(5) NOT NULL,
  REASON VARCHAR2(200),
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT UQ_RESERVATION_BLOCK_DAY_TIME UNIQUE (BLOCK_DATE, BLOCK_TIME)
);
CREATE INDEX IX_RESERVATION_BLOCK_DATE ON RESERVATION_BLOCK_TB (BLOCK_DATE);

