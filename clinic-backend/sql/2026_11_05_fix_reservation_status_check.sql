-- AHNS 노쇼/방문완료 상태 CHECK 제약조건 수정 (Oracle 19c+)
-- 대상: PLASTIC_USR 계정의 RESERVATION_TB
-- 기존 CK_RESERVATION_STATUS의 모든 허용 조건을 보존하고 '노쇼', '방문완료'만 추가합니다.
-- 운영 DB 백업 후 관리자와 협의한 점검 시간에 실행하세요.
-- SQL Developer: F5 (Run Script)로 전체 블록을 실행합니다.
-- DDL은 자동 COMMIT되므로 실행 전 DB 백업을 권장합니다.

-- 실행 전 기존 규칙 확인:
SELECT CONSTRAINT_NAME, SEARCH_CONDITION_VC
FROM USER_CONSTRAINTS
WHERE TABLE_NAME='RESERVATION_TB'
  AND CONSTRAINT_NAME='CK_RESERVATION_STATUS'
  AND CONSTRAINT_TYPE='C';

DECLARE
  v_old_condition VARCHAR2(4000);
BEGIN
  SELECT SEARCH_CONDITION_VC INTO v_old_condition
  FROM USER_CONSTRAINTS
  WHERE TABLE_NAME='RESERVATION_TB'
    AND CONSTRAINT_NAME='CK_RESERVATION_STATUS'
    AND CONSTRAINT_TYPE='C';

  IF v_old_condition IS NULL OR LENGTH(v_old_condition) >= 3800 THEN
    RAISE_APPLICATION_ERROR(-20001, '기존 CHECK 조건을 안전하게 읽을 수 없습니다.');
  END IF;

  IF INSTR(v_old_condition, '''노쇼''') > 0
    AND INSTR(v_old_condition, '''방문완료''') > 0 THEN
    DBMS_OUTPUT.PUT_LINE('기존 CHECK 조건이 이미 노쇼/방문완료를 허용합니다.');
  ELSE
    -- 기존 조건을 제거하기 전에 확장 조건을 먼저 생성하여 보호 공백을 최소화합니다.
    EXECUTE IMMEDIATE
      'ALTER TABLE RESERVATION_TB ADD CONSTRAINT CK_RESERVATION_STATUS_V2 ' ||
      'CHECK ((' || v_old_condition || ') OR ("STATUS" IN (''노쇼'', ''방문완료'')))';

    EXECUTE IMMEDIATE
      'ALTER TABLE RESERVATION_TB DROP CONSTRAINT CK_RESERVATION_STATUS';

    EXECUTE IMMEDIATE
      'ALTER TABLE RESERVATION_TB RENAME CONSTRAINT CK_RESERVATION_STATUS_V2 TO CK_RESERVATION_STATUS';
    DBMS_OUTPUT.PUT_LINE('CK_RESERVATION_STATUS 변경 완료');
  END IF;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20002, 'CK_RESERVATION_STATUS를 찾을 수 없습니다. DB 사용자/테이블 확인 필요.');
END;
/

-- 실행 후 새 허용 조건 확인:
SELECT CONSTRAINT_NAME, SEARCH_CONDITION_VC
FROM USER_CONSTRAINTS
WHERE TABLE_NAME='RESERVATION_TB'
  AND CONSTRAINT_NAME='CK_RESERVATION_STATUS'
  AND CONSTRAINT_TYPE='C';

