-- AHN'S 예약 안내 2차: SOLAPI SMS/카카오 알림톡 발송 요청 대기열 및 정책
-- Oracle SQL Developer F5 실행. DB 백업 후 적용.
-- 기본 ENABLED=0: 연결 정보/승인된 템플릿 설정 전 절대로 외부 발송하지 않습니다.
-- DB 재실행 가능하도록 테이블 존재 여부를 먼저 확인합니다.
DECLARE N NUMBER;
BEGIN
  SELECT COUNT(*) INTO N FROM USER_TABLES WHERE TABLE_NAME='RESERVATION_MESSAGE_POLICY_TB';
  IF N=0 THEN EXECUTE IMMEDIATE q'[
    CREATE TABLE RESERVATION_MESSAGE_POLICY_TB (
      ID NUMBER PRIMARY KEY,
      ENABLED NUMBER(1) DEFAULT 0 NOT NULL,
      CHANNEL VARCHAR2(10 CHAR) DEFAULT 'SMS' NOT NULL,
      SEND_CREATED NUMBER(1) DEFAULT 1 NOT NULL,
      SEND_RESCHEDULED NUMBER(1) DEFAULT 1 NOT NULL,
      SEND_CANCELLED NUMBER(1) DEFAULT 1 NOT NULL,
      SEND_REMINDER NUMBER(1) DEFAULT 1 NOT NULL,
      REMINDER_HOURS NUMBER(3) DEFAULT 24 NOT NULL,
      START_HOUR NUMBER(2) DEFAULT 9 NOT NULL,
      END_HOUR NUMBER(2) DEFAULT 20 NOT NULL,
      UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
      CONSTRAINT CK_RES_MSG_CHANNEL CHECK (CHANNEL IN ('SMS','KAKAO')),
      CONSTRAINT CK_RES_MSG_ENABLE CHECK (ENABLED IN (0,1)),
      CONSTRAINT CK_RES_MSG_HOURS CHECK (REMINDER_HOURS IN (12,24,48,72)),
      CONSTRAINT CK_RES_MSG_WINDOW CHECK (START_HOUR >= 0 AND END_HOUR <= 24 AND END_HOUR > START_HOUR)
    )
  ]'; END IF;
END;
/
MERGE INTO RESERVATION_MESSAGE_POLICY_TB P USING (SELECT 1 ID FROM DUAL) S
  ON (P.ID=S.ID)
  WHEN NOT MATCHED THEN INSERT
    (ID,ENABLED,CHANNEL,SEND_CREATED,SEND_RESCHEDULED,SEND_CANCELLED,SEND_REMINDER,REMINDER_HOURS,START_HOUR,END_HOUR)
    VALUES (1,0,'SMS',1,1,1,1,24,9,20);

DECLARE N NUMBER;
BEGIN
  SELECT COUNT(*) INTO N FROM USER_TABLES WHERE TABLE_NAME='RESERVATION_MESSAGE_TB';
  IF N=0 THEN EXECUTE IMMEDIATE q'[
    CREATE TABLE RESERVATION_MESSAGE_TB (
      ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
      RESERVATION_ID NUMBER NOT NULL,
      EVENT_TYPE VARCHAR2(20 CHAR) NOT NULL,
      SLOT_KEY VARCHAR2(16 CHAR) NOT NULL,
      DEDUPE_KEY VARCHAR2(120 CHAR) NOT NULL,
      DUE_AT_KST VARCHAR2(16 CHAR) NOT NULL,
      CHANNEL VARCHAR2(10 CHAR) NOT NULL,
      STATE VARCHAR2(20 CHAR) DEFAULT 'QUEUED' NOT NULL,
      ATTEMPTS NUMBER DEFAULT 0 NOT NULL,
      LAST_ERROR VARCHAR2(400 CHAR) NULL,
      PROVIDER_REF VARCHAR2(100 CHAR) NULL,
      ACCEPTED_AT TIMESTAMP NULL,
      CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
      UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
      CONSTRAINT FK_RES_MESSAGE_RES FOREIGN KEY (RESERVATION_ID) REFERENCES RESERVATION_TB(ID),
      CONSTRAINT UQ_RES_MESSAGE_DEDUPE UNIQUE (DEDUPE_KEY),
      CONSTRAINT CK_RES_MSG_TYPE CHECK (EVENT_TYPE IN ('CREATED','RESCHEDULED','CANCELLED','REMINDER')),
      CONSTRAINT CK_RES_MSG_STATE CHECK (STATE IN ('QUEUED','PROCESSING','ACCEPTED','FAILED','UNKNOWN','SKIPPED','CANCELLED')),
      CONSTRAINT CK_RES_MSG_MODE CHECK (CHANNEL IN ('SMS','KAKAO'))
    )
  ]'; END IF;
END;
/
DECLARE N NUMBER;
BEGIN
  SELECT COUNT(*) INTO N FROM USER_INDEXES WHERE INDEX_NAME='IX_RES_MESSAGE_DUE';
  IF N=0 THEN EXECUTE IMMEDIATE
    'CREATE INDEX IX_RES_MESSAGE_DUE ON RESERVATION_MESSAGE_TB (STATE,DUE_AT_KST)';
  END IF;
END;
/
COMMIT;
