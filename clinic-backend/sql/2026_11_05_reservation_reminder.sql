-- 외부 SMS/알림톡 서비스가 없으므로 READY = 발송 완료가 아닙니다.

DECLARE N NUMBER;
BEGIN
  SELECT COUNT(*) INTO N FROM USER_TAB_COLUMNS
  WHERE TABLE_NAME='RESERVATION_TB' AND COLUMN_NAME='VISIT_CONFIRMED_AT';
  IF N=0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE RESERVATION_TB ADD VISIT_CONFIRMED_AT TIMESTAMP NULL';
  END IF;
END;
/

DECLARE N NUMBER;
BEGIN
  SELECT COUNT(*) INTO N FROM USER_TABLES WHERE TABLE_NAME='RESERVATION_REMINDER_TB';
  IF N=0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE RESERVATION_REMINDER_TB (
        ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
        RESERVATION_ID NUMBER NOT NULL,
        SLOT_KEY VARCHAR2(16 CHAR) NOT NULL,
        DUE_AT_KST VARCHAR2(16 CHAR) NOT NULL,
        STATE VARCHAR2(20 CHAR) DEFAULT 'PENDING' NOT NULL,
        READY_AT TIMESTAMP NULL,
        CONTACTED_AT TIMESTAMP NULL,
        CONTACTED_BY VARCHAR2(50 CHAR) NULL,
        CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
        UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
        CONSTRAINT FK_RES_REMINDER_RES FOREIGN KEY (RESERVATION_ID) REFERENCES RESERVATION_TB(ID),
        CONSTRAINT UQ_RES_REMINDER_RES UNIQUE (RESERVATION_ID),
        CONSTRAINT CK_RES_REMINDER_STATE CHECK (STATE IN ('PENDING','READY','CONTACTED','CANCELLED'))
      )
    ]';
  END IF;
END;
/

DECLARE N NUMBER;
BEGIN
  SELECT COUNT(*) INTO N FROM USER_INDEXES WHERE INDEX_NAME='IX_RES_REMINDER_DUE';
  IF N=0 THEN EXECUTE IMMEDIATE
    'CREATE INDEX IX_RES_REMINDER_DUE ON RESERVATION_REMINDER_TB(STATE,DUE_AT_KST)';
  END IF;
END;
/

-- 이미 예약된 건 중 미래의 활성 예약에 대해서도 최초 안내 일정을 등록합니다.
-- KST 고정 문자열(YYYY-MM-DD HH24:MI)로 서버 시간대와 무관하게 비교합니다.
MERGE INTO RESERVATION_REMINDER_TB R
USING (
 SELECT ID AS RID, SLOT_DATE || ' ' || SLOT_TIME AS SLOT_KEY,
   TO_CHAR(TO_TIMESTAMP(SLOT_DATE || ' ' || SLOT_TIME,'YYYY-MM-DD HH24:MI') - INTERVAL '1' DAY,
     'YYYY-MM-DD HH24:MI') AS DUE_AT_KST
 FROM RESERVATION_TB
 WHERE STATUS IN ('예약대기','예약확정')
   AND SLOT_DATE || ' ' || SLOT_TIME > TO_CHAR(SYSTIMESTAMP AT TIME ZONE 'Asia/Seoul','YYYY-MM-DD HH24:MI')
) S ON (R.RESERVATION_ID=S.RID)
WHEN NOT MATCHED THEN INSERT (RESERVATION_ID,SLOT_KEY,DUE_AT_KST,STATE)
 VALUES (S.RID,S.SLOT_KEY,S.DUE_AT_KST,'PENDING');
COMMIT;

SELECT STATE, COUNT(*) AS CNT FROM RESERVATION_REMINDER_TB GROUP BY STATE;
