-- AHN'S 상담 운영 / 관리자 알림 / 방문·노쇼 관리
-- 대상: OracleDB 19c+ (IDENTITY 지원)
-- 반드시 기존 테이블 백업 후, 한 번만 순서대로 실행하세요.
-- 기존 CONSULT.ID 및 RESERVATION_TB.ID 값은 절대 변경하지 않습니다.
-- SQL Developer에서 Ctrl+Enter 단독 실행 시 각 문장별로 나눠 실행합니다.

-- 1. CONSULT: 접수번호, 비회원 조회 코드 해시, 최종 답변, 담당자
ALTER TABLE CONSULT ADD (
  RECEIPT_NO VARCHAR2(40),
  LOOKUP_HASH VARCHAR2(64),
  ANSWER_TEXT CLOB,
  ANSWERED_AT TIMESTAMP,
  ASSIGNED_TO VARCHAR2(50)
);

-- 2. 고객용 번호는 내부 ID와 무관한 독립 시퀀스. 한 번 생성하면 재설정하지 마세요.
CREATE SEQUENCE CONSULT_RECEIPT_SEQ START WITH 1 INCREMENT BY 1 NOCYCLE CACHE 20;

-- 3. 기존 상담 데이터에도 접수번호를 부여합니다. 이전 고객은 조회코드가 없으므로
--    비회원 답변 조회는 신규 신청에만 가능합니다. 기존 데이터는 상담실 직접 확인 필요.
UPDATE CONSULT
SET RECEIPT_NO = 'AHNS-' ||
  TO_CHAR(NVL(CREATED_AT, CAST(SYSTIMESTAMP AS TIMESTAMP)), 'YYYYMMDD') || '-' ||
  LPAD(TO_CHAR(CONSULT_RECEIPT_SEQ.NEXTVAL), 6, '0')
WHERE RECEIPT_NO IS NULL;
COMMIT;

ALTER TABLE CONSULT MODIFY (RECEIPT_NO NOT NULL);
CREATE UNIQUE INDEX UQ_CONSULT_RECEIPT_NO ON CONSULT (RECEIPT_NO);

-- 4. 관리자 상담 처리 기록 (내부 메모/통화/상태변경/답변)
CREATE TABLE CONSULT_ACTIVITY_TB (
  ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  CONSULT_ID NUMBER NOT NULL,
  KIND VARCHAR2(30) NOT NULL,
  NOTE_TEXT CLOB,
  ADMIN_USER_ID VARCHAR2(50) NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT FK_CONSULT_ACTIVITY FOREIGN KEY (CONSULT_ID) REFERENCES CONSULT(ID) ON DELETE CASCADE
);
CREATE INDEX IX_CONSULT_ACTIVITY_CONSULT ON CONSULT_ACTIVITY_TB (CONSULT_ID, ID);

-- 5. 관리자 알림 이력: 의료내용·환자 이름·연락처를 저장하지 않습니다.
CREATE TABLE ADMIN_NOTIFICATION_TB (
  ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  CATEGORY VARCHAR2(30) NOT NULL,
  REFERENCE_ID NUMBER NOT NULL,
  MESSAGE VARCHAR2(200 CHAR) NOT NULL,
  IS_READ NUMBER(1) DEFAULT 0 NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT CK_ADMIN_NOTIFICATION_READ CHECK (IS_READ IN (0,1))
);
CREATE INDEX IX_ADMIN_NOTIFICATION_UNREAD ON ADMIN_NOTIFICATION_TB (IS_READ, ID);

-- 6. 온라인 방문예약(RESERVATION_TB) 상태 변경 감사기록
--    기존 예약 상태 컬럼 길이(VARCHAR2(20)) 내에서 '방문완료'/'노쇼'/'판정취소' 사용
CREATE TABLE RESERVATION_STATUS_AUDIT_TB (
  ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  RESERVATION_ID NUMBER NOT NULL,
  PREVIOUS_STATUS VARCHAR2(20) NOT NULL,
  NEXT_STATUS VARCHAR2(20) NOT NULL,
  REASON VARCHAR2(500 CHAR) NOT NULL,
  ADMIN_USER_ID VARCHAR2(50) NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT FK_RES_STATUS_AUDIT FOREIGN KEY (RESERVATION_ID) REFERENCES RESERVATION_TB(ID)
);
CREATE INDEX IX_RES_STATUS_AUDIT_REF ON RESERVATION_STATUS_AUDIT_TB (RESERVATION_ID, ID);

-- 완료 확인 SQL
SELECT COUNT(*) AS CONSULT_TOTAL, COUNT(RECEIPT_NO) AS WITH_RECEIPT,
       COUNT(DISTINCT RECEIPT_NO) AS UNIQUE_RECEIPTS FROM CONSULT;
SELECT SEQUENCE_NAME, LAST_NUMBER FROM USER_SEQUENCES WHERE SEQUENCE_NAME = 'CONSULT_RECEIPT_SEQ';
SELECT TABLE_NAME FROM USER_TABLES WHERE TABLE_NAME IN
  ('CONSULT_ACTIVITY_TB','ADMIN_NOTIFICATION_TB','RESERVATION_STATUS_AUDIT_TB');
