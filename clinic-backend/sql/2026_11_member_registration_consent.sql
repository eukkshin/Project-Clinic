-- 2) 가입 시 확인·동의 내역을 서버 기준 시각으로 보존
CREATE TABLE MEMBER_REGISTRATION_CONSENT (
  CONSENT_IDX NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  USER_IDX NUMBER NOT NULL,
  CONSENT_TYPE VARCHAR2(32) NOT NULL,
  STATUS CHAR(1) NOT NULL,
  POLICY_VERSION VARCHAR2(60) NOT NULL,
  RECORDED_AT TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
  CONSTRAINT PK_MEMBER_REG_CONSENT PRIMARY KEY (CONSENT_IDX),
  CONSTRAINT FK_MEMBER_REG_CONSENT_MEMBER
    FOREIGN KEY (USER_IDX) REFERENCES MEMBER_TB(USER_IDX),
  CONSTRAINT UQ_MEMBER_REG_CONSENT UNIQUE (USER_IDX, CONSENT_TYPE),
  CONSTRAINT CK_MEMBER_REG_CONSENT_STATUS CHECK (STATUS IN ('Y','N')),
  CONSTRAINT CK_MEMBER_REG_CONSENT_TYPE CHECK (
    CONSENT_TYPE IN ('TERMS','PRIVACY_NOTICE','MARKETING_EMAIL','MARKETING_SMS')
  )
);

