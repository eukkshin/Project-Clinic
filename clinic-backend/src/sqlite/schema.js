"use strict";
// SQLite-only application schema for tables formerly created by Oracle SQL migrations.
// Creates missing tables; does not delete or rewrite existing data.
const DDL = [
  `CREATE TABLE IF NOT EXISTS CONSULT_RECEIPT_COUNTER
    (ID INTEGER PRIMARY KEY AUTOINCREMENT)`,
  `CREATE TABLE IF NOT EXISTS RESERVATION_BOOKING_LOCK_TB
    (LOCK_ID INTEGER PRIMARY KEY CHECK (LOCK_ID = 1))`,
  `CREATE TABLE IF NOT EXISTS SEARCH_KEYWORD_LOG_TB
    (ID INTEGER PRIMARY KEY AUTOINCREMENT, KEYWORD TEXT NOT NULL,
     SEARCHED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP)`,
  `CREATE INDEX IF NOT EXISTS IDX_SEARCH_LOG_TIME ON SEARCH_KEYWORD_LOG_TB(SEARCHED_AT)`,
  `CREATE TABLE IF NOT EXISTS MEMBER_REGISTRATION_CONSENT
    (CONSENT_IDX INTEGER PRIMARY KEY AUTOINCREMENT, USER_IDX INTEGER NOT NULL,
     CONSENT_TYPE TEXT NOT NULL, STATUS TEXT NOT NULL, POLICY_VERSION TEXT NOT NULL,
     RECORDED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP)`,
  `CREATE TABLE IF NOT EXISTS ACCOUNT_CONSENT_HISTORY
    (ID INTEGER PRIMARY KEY AUTOINCREMENT, USER_IDX INTEGER NOT NULL,
     CHANNEL TEXT NOT NULL, PREVIOUS_VALUE TEXT NOT NULL,
     NEW_VALUE TEXT NOT NULL, CHANGED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP)`,
  `CREATE TABLE IF NOT EXISTS PASSWORD_RESET_TOKEN
    (ID INTEGER PRIMARY KEY AUTOINCREMENT, USER_IDX INTEGER NOT NULL,
     TOKEN_HASH TEXT NOT NULL UNIQUE, EXPIRES_AT TEXT NOT NULL,
     USED_AT TEXT DEFAULT NULL)`,
  `CREATE INDEX IF NOT EXISTS IDX_PASSWORD_RESET_USER ON PASSWORD_RESET_TOKEN(USER_IDX)`,
  `CREATE TABLE IF NOT EXISTS ACCOUNT_EMAIL_CHANGE_TOKEN
    (ID INTEGER PRIMARY KEY AUTOINCREMENT, USER_IDX INTEGER NOT NULL,
     TOKEN_HASH TEXT NOT NULL UNIQUE, OLD_EMAIL TEXT NOT NULL,
     NEW_EMAIL TEXT NOT NULL, EXPIRES_AT TEXT NOT NULL,
     USED_AT TEXT DEFAULT NULL)`,
  `CREATE TABLE IF NOT EXISTS SOCIAL_AUTH_FLOW_TB
    (STATE_HASH TEXT PRIMARY KEY, PROVIDER TEXT NOT NULL,
     CODE_VERIFIER TEXT NOT NULL, NONCE TEXT NOT NULL,
     INTENT TEXT NOT NULL, USER_IDX INTEGER, LOCALE TEXT,
     EXPIRES_AT TEXT NOT NULL, USED_AT TEXT)`,
  `CREATE TABLE IF NOT EXISTS SOCIAL_SIGNUP_PENDING_TB
    (TOKEN_HASH TEXT PRIMARY KEY, PROVIDER TEXT NOT NULL,
     PROVIDER_USER_ID TEXT NOT NULL, LOCALE TEXT,
     EXPIRES_AT TEXT NOT NULL, USED_AT TEXT)`,
  `CREATE TABLE IF NOT EXISTS SOCIAL_ACCOUNT_TB
    (SOCIAL_ID INTEGER PRIMARY KEY AUTOINCREMENT, USER_IDX INTEGER NOT NULL,
     PROVIDER TEXT NOT NULL, PROVIDER_USER_ID TEXT NOT NULL,
     LINKED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
     LAST_LOGIN_AT TEXT,
     UNIQUE(PROVIDER, PROVIDER_USER_ID), UNIQUE(USER_IDX, PROVIDER))`,
];

async function ensureSqliteSchema(dataSource) {
  if (dataSource.options.type !== "better-sqlite3") {
    throw new Error("SQLite application expected a better-sqlite3 DataSource");
  }
  for (const sql of DDL) await dataSource.query(sql);
  await dataSource.query(
    "INSERT OR IGNORE INTO RESERVATION_BOOKING_LOCK_TB (LOCK_ID) VALUES (1)",
  );
}
module.exports = { ensureSqliteSchema };
